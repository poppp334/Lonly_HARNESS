def fence_untrusted(content: str, source: str = "tool_output") -> str:
    """Wrap untrusted external content in provenance fence tags.

    Mitigates indirect prompt injection by clearly delineating untrusted
    data boundaries so the LLM can distinguish system instructions from
    external observations.

    Format:
        <untrusted_observation source="tool_name" provenance="tool_output">
        ... raw content ...
        </untrusted_observation>
    """
    if not content or not isinstance(content, str):
        return content
    return (
        f'<untrusted_observation source="{source}" provenance="tool_output">\n'
        f"{content}\n"
        f"</untrusted_observation>"
    )


def strip_fences(text: str) -> str:
    """Strip provenance fence tags from text (for display/logging)."""
    import re
    return re.sub(
        r'</?untrusted_observation[^>]*>\n?',
        '',
        text,
    ).strip()


